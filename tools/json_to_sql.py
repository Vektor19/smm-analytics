"""Converts data/*.json into db/seed.sql (INSERT statements for the tables in db/schema.sql).

Usage: python tools/json_to_sql.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(name):
    with open(os.path.join(ROOT, "data", f"{name}.json"), encoding="utf-8") as f:
        return json.load(f)["items"]


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    return "N'" + str(v).replace("'", "''") + "'"


def inserts(table, columns, rows, batch=500):
    out = []
    for i in range(0, len(rows), batch):
        values = ",\n".join("(" + ", ".join(sql(v) for v in r) + ")" for r in rows[i:i + batch])
        out.append(f"INSERT INTO dbo.{table} ({', '.join(columns)}) VALUES\n{values};")
    return "\n".join(out)


def main():
    accounts = load("accounts")
    daily = load("daily_stats")
    posts = load("posts")
    parts = [
        "-- Generated by tools/json_to_sql.py from data/*.json. Run db/schema.sql first.",
        "SET NOCOUNT ON;",
        inserts("Accounts", ["Id", "Platform", "Handle", "Name", "Color"],
                [[a["id"], a["platform"], a["handle"], a["name"], a["color"]] for a in accounts]),
        inserts("DailyStats", ["AccountId", "[Date]", "Followers", "NewFollowers", "Unfollows", "Reach", "Impressions",
                               "Likes", "Comments", "Shares", "Saves", "ProfileVisits"],
                [[d["accountId"], d["date"], d["followers"], d["newFollowers"], d["unfollows"], d["reach"], d["impressions"],
                  d["likes"], d["comments"], d["shares"], d["saves"], d["profileVisits"]] for d in daily]),
        inserts("Posts", ["Id", "AccountId", "[Type]", "Title", "PublishedAt", "FollowersAtPublish", "Reach", "Impressions",
                          "Likes", "Comments", "Shares", "Saves", "VideoViews"],
                [[p["id"], p["accountId"], p["type"], p["title"], p["publishedAt"], p["followersAtPublish"], p["reach"],
                  p["impressions"], p["likes"], p["comments"], p["shares"], p["saves"], p["videoViews"]] for p in posts]),
        "SELECT (SELECT COUNT(*) FROM dbo.Accounts) AS Accounts, (SELECT COUNT(*) FROM dbo.DailyStats) AS DailyStats, "
        "(SELECT COUNT(*) FROM dbo.Posts) AS Posts;",
    ]
    path = os.path.join(ROOT, "db", "seed.sql")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n\n".join(parts) + "\n")
    print(f"written {path}: {len(accounts)} accounts, {len(daily)} daily rows, {len(posts)} posts")


if __name__ == "__main__":
    main()
